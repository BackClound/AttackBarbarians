/// <summary>
/// 元素类型，用于元素附加伤害与后续抗性系统。
/// </summary>
/// <remarks>纯枚举，无需挂载。</remarks>
public enum ElementType
{
    /// <summary>无元素。</summary>
    None = 0,
    /// <summary>物理伤害。</summary>
    Physical = 1,
    /// <summary>火元素伤害。</summary>
    Fire = 2,
    /// <summary>冰元素伤害。</summary>
    Ice = 3,
    /// <summary>雷元素伤害。</summary>
    Lightning = 4
}
